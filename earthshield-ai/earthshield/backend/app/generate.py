"""Seeded SIMULATED data generator. Nothing here is real satellite/weather data. Demo polygons are NOT official boundaries."""
import json, math, os, sys
import numpy as np, pandas as pd
from .geo import area_m2
SEED = 42
ZONES = [("Z01","Demo Zone A (Krishna-like)","rice",16.30,80.40),("Z02","Demo Zone B (Guntur-like)","cotton",16.35,80.95),
         ("Z03","Demo Zone C (Khammam-like)","maize",17.20,80.15),("Z04","Demo Zone D (Godavari-like)","rice",16.90,81.60),
         ("Z05","Demo Zone E (Prakasam-like)","chilli",15.50,79.90),("Z06","Demo Zone F (Warangal-like)","cotton",17.95,79.60)]
CROPS = {"rice": (3.5, 22000), "cotton": (2.0, 65000), "maize": (5.0, 20000), "chilli": (2.5, 150000)}  # t/ha, INR/t  (ASSUMPTIONS)
RAIN = [5,5,8,15,40,110,160,170,150,100,40,10]
def box(lon, lat, w, h): return [[lon,lat],[lon+w,lat],[lon+w,lat+h],[lon,lat+h],[lon,lat]]
def main(out="data"):
    os.makedirs(out, exist_ok=True); rng = np.random.default_rng(SEED)
    feats = []
    for zid, name, crop, lat, lon in ZONES:
        ring = box(lon, lat, 0.30, 0.25); frac = round(float(rng.uniform(0.35, 0.55)), 2)
        ha = round(area_m2(ring)/1e4*frac, -1)
        feats.append({"type":"Feature","properties":{"region_id":zid,"name":name,"crop":crop,"cultivated_ha":ha,"season":"Kharif","label":"SIMULATED DEMO POLYGON - not an official boundary"},"geometry":{"type":"Polygon","coordinates":[ring]}})
    json.dump({"type":"FeatureCollection","features":feats}, open(f"{out}/regions.geojson","w"))
    rows = []
    for zid, _, crop, lat, lon in ZONES:
        f = float(rng.uniform(0.85, 1.15))
        for y in range(2019, 2026):
            for m in range(1, 13):
                if y == 2025 and m > 10: continue
                nd = 0.35 + 0.25*math.sin(2*math.pi*(m-4)/12) + rng.normal(0, .03)
                rn = RAIN[m-1]*f*rng.lognormal(0, .25)
                tc = 28 + 6*math.sin(2*math.pi*(m-3)/12) + rng.normal(0, .6)
                if zid == "Z06" and y == 2025 and m >= 9: continue          # stale/incomplete series
                if zid == "Z05" and y == 2025 and m == 7: continue          # missing month
                if y == 2025 and 6 <= m <= 9:
                    if zid == "Z03": nd -= 0.14; rn *= 0.4
                    if zid == "Z05": rn *= 0.65
                rows.append((zid, f"{y}-{m:02d}-01", round(nd,4), round(rn,1), round(tc,1), "SIMULATED"))
    pd.DataFrame(rows, columns=["region_id","date","ndvi","rainfall_mm","temp_c","data_type"]).to_csv(f"{out}/observations.csv", index=False)
    z = {r[0]:r for r in ZONES}
    def fz(zid, x0, x1, y0, y1):
        _, _, _, lat, lon = z[zid]; return box(lon+0.30*x0, lat+0.25*y0, 0.30*(x1-x0), 0.25*(y1-y0))
    fl = [("F1",fz("Z02",.6,1.1,-.1,1.1)),("F2",fz("Z02",.85,1.2,.3,.7)),("F3",fz("Z04",-.1,1.1,-.2,.2))]
    json.dump({"type":"FeatureCollection","features":[{"type":"Feature","properties":{"flood_id":i,"observed":"2025-09-12","data_type":"SIMULATED","source":"synthetic scenario"},"geometry":{"type":"Polygon","coordinates":[r]}} for i,r in fl]}, open(f"{out}/floods.geojson","w"))
    pd.DataFrame([(k,*v,"ASSUMPTION - not market data") for k,v in CROPS.items()], columns=["crop","yield_t_per_ha","price_inr_per_t","note"]).to_csv(f"{out}/crops.csv", index=False)
    pd.DataFrame([("regions.geojson","synthetic","SIMULATED","n/a","generated by app.generate seed 42"),("observations.csv","synthetic","SIMULATED","monthly; ndvi unitless, rain mm, temp C","not real imagery")],
        columns=["file","source","type","units","note"]).to_csv(f"{out}/provenance.csv", index=False)
if __name__ == "__main__": main(sys.argv[1] if len(sys.argv) > 1 else "data")
